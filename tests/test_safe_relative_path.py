# The manifest validator only refused a drive LETTER ("C:x"); every validator now follows
# PureWindowsPath, which takes any single character before ":" for a drive ("1:x"), as the
# other three already did.
MANIFEST_CORRECTIONS = {'1:x': ERR}

# The scan-result validator only refused a LEADING "..": "a/../../b" climbed out of
# the indexed root, and "./a", "a//b" were kept unnormalised so one file could carry
# several spellings. It now follows the shared rules (reject any "..", collapse "." and "").
SNAPSHOT_CORRECTIONS = {
    './a': 'a',
    '.\\a\\b\\': 'a/b',
    'a/./b': 'a/b',
    'a//b': 'a/b',
    'a/./': 'a',
    'a/.': 'a',
    './.': ERR,
    'a/..': ERR,
    'a/../b': ERR,
    'a/../../b': ERR,
    'a/b/..': ERR,
    'a\\..\\b': ERR,
}


def _outcome(function, value: str) -> str:
    try:
        return function(value)
    except ValueError:
        return ERR


def _rows(column: int):
    return [(row[0], row[column]) for row in TABLE]


@pytest.mark.parametrize(("value", "expected"), _rows(1), ids=lambda v: repr(v))
def test_scope_filter_paths_keep_their_answers(value: str, expected: str) -> None:
    assert _outcome(scope_path, value) == expected


@pytest.mark.parametrize(
    ("value", "expected"),
    [(value, MANIFEST_CORRECTIONS.get(value, expected)) for value, expected in _rows(2)],
    ids=lambda v: repr(v),
)
def test_manifest_paths_keep_their_answers(value: str, expected: str) -> None:
    assert _outcome(manifest_path, value) == expected


@pytest.mark.parametrize(("value", "expected"), _rows(4), ids=lambda v: repr(v))
def test_public_mirror_paths_keep_their_answers(value: str, expected: str) -> None:
    assert _outcome(catalog_path, value) == expected


@pytest.mark.parametrize(
    ("value", "expected"),
    [(value, expected) for value, expected in _rows(3) if value not in SNAPSHOT_CORRECTIONS],
    ids=lambda v: repr(v),
)
def test_scan_result_paths_keep_their_answers(value: str, expected: str) -> None:
    assert _outcome(snapshot_path, value) == expected


@pytest.mark.parametrize(("value", "expected"), sorted(SNAPSHOT_CORRECTIONS.items()), ids=lambda v: repr(v))
def test_scan_result_paths_follow_the_shared_rules(value: str, expected: str) -> None:
    assert _outcome(snapshot_path, value) == expected


def test_public_mirror_errors_stay_catalog_errors() -> None:
    with pytest.raises(PublicSourceCatalogError):
        catalog_path("../outside")
    with pytest.raises(PublicSourceCatalogError, match="must omit the .git storage suffix"):
        catalog_path("fixture/sample.git")
